"""Take-home pay: gross base pay minus the taxes a household pays where the job is.

    take-home = gross − federal income tax − Social Security/Medicare − state income tax
                − state payroll taxes − local income taxes

In the config directory:

- taxes.yaml (hand-kept): localities with their own income tax and the cities that pick them, local
  taxes PolicyEngine doesn't model (Ohio, Pennsylvania, Michigan and Kentucky city taxes, Portland
  Metro's housing tax), which taxes count 401(k) money as wages, and approximate tax rates abroad.
- tax_data/<filing>-<children>-<other dependents>.json.gz (generated by tools/build_tax_data.py with
  PolicyEngine-US): US taxes at salaries from $0 to $1M for every state and locality, for each
  household the Settings page offers, with no 401(k). Values between grid points are interpolated.

The household (filing status, dependents, 401(k) share) comes from the Settings page (`household:`).
Pre-tax 401(k) money counts as take-home (it's yours): it only lowers the income each tax is levied
on, so those taxes are read off the table at gross pay minus the 401(k); Social Security, Medicare,
state payroll taxes, Pennsylvania's income tax and wage taxes (Philadelphia, ...) stay on gross pay.
Taxes follow where you live, and the job's city is taken as that; a remote job takes the reference
location.
"""
from __future__ import annotations

import gzip
import json
from bisect import bisect_right
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

import yaml

PARTS = ("federal", "fica", "state", "state_payroll", "local")
PART_LABELS = {"federal": "federal income tax", "fica": "Social Security + Medicare", "state": "state income tax",
               "state_payroll": "state payroll (SDI, paid leave)", "local": "local income tax"}
ABROAD_POINTS = (100_000, 250_000)  # gross USD the `abroad` rates in taxes.yaml are given at
ON_GROSS = {"fica", "state_payroll"}  # never lowered by the 401(k)
MAX_CHILDREN, MAX_OTHER = 4, 1


def variant_name(household: dict) -> str:
    """The prebuilt table for a household (more dependents than the tables have count as the most)."""
    filing = "joint" if household.get("filing") == "joint" else "single"
    return (f"{filing}-{min(int(household.get('children', 0)), MAX_CHILDREN)}-"
            f"{min(int(household.get('other_dependents', 0)), MAX_OTHER)}")


@dataclass
class TakeHome:
    gross: float                                        # US dollars a year
    where: str                                          # which tax rules applied
    parts: dict[str, float] = field(default_factory=dict)  # label -> dollars

    @property
    def taxes(self) -> float:
        return sum(self.parts.values())

    @property
    def net(self) -> float:
        return self.gross - self.taxes

    def text(self) -> str:
        if not self.gross:
            return "no pay"
        items = [f"{label} ${v:,.0f}" for label, v in self.parts.items() if round(v)]
        total = f"${self.taxes:,.0f} ({self.taxes / self.gross:.1%})"
        return f"{' + '.join(items)} = {total}" if len(items) > 1 else f"{items[0]} ({self.taxes / self.gross:.1%})" if items else "no taxes"


def _interp(xs: list[int], ys: list[int], x: float) -> float:
    """Straight line between grid points; past the last point, the last segment's slope."""
    i = min(max(bisect_right(xs, x) - 1, 0), len(xs) - 2)
    x0, x1, y0, y1 = xs[i], xs[i + 1], ys[i], ys[i + 1]
    return y0 + (y1 - y0) * (x - x0) / (x1 - x0)


class Taxes:
    def __init__(self, rules: dict, data: dict, household: dict | None = None):
        self.rules, self.data = rules, data
        self.household = {"filing": "single", "children": 0, "other_dependents": 0, "k401_rate": 0.0,
                          **(household or {})}
        if data.get("k401") != 0:
            raise ValueError("this tax table is from before household variants; rebuild with tools/build_tax_data.py")
        self.year: int = data["year"]
        self.k401_rate = float(self.household["k401_rate"])
        self.k401_limit = float(rules.get("k401_limit", 0) or 0)
        self.wages: list[int] = data["wages"]
        self.places: dict[str, dict[str, list[int]]] = data["places"]
        self.localities: dict[str, dict] = rules.get("localities") or {}
        missing = [k for k in self.localities if k not in self.places]
        if missing or "US" not in self.places:
            raise ValueError(f"the tax table has no data for {', '.join(missing) or 'US'}; rebuild it")
        self.wage_states = set(rules.get("wage_based_states") or [])
        self.extras: list[dict] = rules.get("local_extras") or []
        self.abroad: dict[str, list[float]] = rules.get("abroad") or {}

    @classmethod
    def load(cls, rules_path: Path, data_dir: Path, household: dict | None = None) -> Taxes:
        rules = yaml.safe_load(rules_path.read_text(encoding="utf-8"))
        path = data_dir / f"{variant_name(household or {})}.json.gz"
        return cls(rules, json.loads(gzip.decompress(path.read_bytes())), household)

    def describe(self) -> str:
        h = self.household
        who = "married filing jointly, one earner" if h["filing"] == "joint" else "single"
        deps = h["children"] + h["other_dependents"]
        kids = f", {h['children']} child{'ren' if h['children'] != 1 else ''} under 17" if h["children"] else ""
        other = f", {h['other_dependents']} other dependent{'s' if h['other_dependents'] != 1 else ''}" if h["other_dependents"] else ""
        return f"{who}{kids}{other}{'' if deps else ', no dependents'}, {self.k401_rate:.0%} pre-tax 401(k)"

    def problem(self, today: date | None = None) -> str:
        """Why the tax table may be out of date ("" when it isn't); shown in the digest."""
        if (today or date.today()).year > self.year:
            return (f"taxes are {self.year}'s; rebuild config/tax_data/ for {(today or date.today()).year} "
                    "with tools/build_tax_data.py once PolicyEngine-US has the new brackets")
        return ""

    def place_key(self, state: str, city: str) -> str:
        """The tax_data.json table for a US place: a locality by city, the state's default locality,
        the state, or "US" (the average of the states) when the state isn't known."""
        if not state or state not in self.places:
            return "US"
        city = city.lower()
        default = state
        for key, loc in self.localities.items():
            if loc["state"] != state:
                continue
            if city and city in loc.get("cities", []):
                return key
            if loc.get("default"):
                default = key
        return default

    def take_home(self, gross_usd: float, country: str = "USA", state: str = "", city: str = "") -> TakeHome:
        gross = max(gross_usd, 0.0)
        if country != "USA":
            lo, hi = self.abroad.get(country) or self.abroad.get("default") or (0.0, 0.0)
            (x0, x1) = ABROAD_POINTS
            rate = lo if gross <= x0 else hi if gross >= x1 else lo + (hi - lo) * (gross - x0) / (x1 - x0)
            known = "" if country in self.abroad else ", country not listed: typical rate"
            return TakeHome(gross, f"{country} (approximate{known})", {"income tax + social insurance": gross * rate})
        key = self.place_key(state, city)
        table = self.places[key]
        k401 = min(gross * self.k401_rate, self.k401_limit) if self.k401_limit else gross * self.k401_rate
        on_wages = {"state"} if state in self.wage_states else set()
        if self.localities.get(key, {}).get("base") == "wages":
            on_wages.add("local")
        parts = {PART_LABELS[p]: _interp(self.wages, table[p], gross if p in ON_GROSS | on_wages else gross - k401)
                 for p in PARTS if p in table}
        from .col import STATES  # col imports this module
        where = self.localities[key]["label"] if key in self.localities else STATES.get(key, "US average of states")
        for rule in self.extras:
            if rule["state"] != state:
                continue
            rate = (rule.get("cities") or {}).get(city.lower(), rule.get("default", 0.0))
            base = gross - k401 if rule.get("base") == "agi" else gross
            tax = rate * max(0.0, base - rule.get("over", 0))
            if tax:
                parts[rule["label"]] = parts.get(rule["label"], 0.0) + tax
        return TakeHome(gross, f"{where}, {self.year} taxes", parts)
